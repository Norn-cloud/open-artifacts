import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Vendors MediaPipe Selfie Segmentation as a self-hosted, same-origin bundle
// under public/vendor/mediapipe/ so the handoff webcam can run portrait
// segmentation without a CDN fetch (the viewer CSP stays unchanged; the host
// page's script-src 'self' + connect-src 'self' cover the same-origin WASM
// + asset loads). Mirrors the mermaid self-host convention
// (scripts/vendor-mermaid.mjs -> public/vendor/mermaid.runtime.js).
//
// This is a MANUAL vendor step (like subset-cjk-font.py / vendor-mermaid.mjs):
// run it once when bumping the pinned version. The generated files are
// committed. Do not hand-edit the output.
//
//   node scripts/vendor-mediapipe.mjs
//
// Outputs:
//   public/vendor/mediapipe/selfie_segmentation.js              (IIFE loader)
//   public/vendor/mediapipe/selfie_segmentation_solution*.wasm   (both WASM variants)
//   public/vendor/mediapipe/selfie_segmentation_solution*.js     (WASM glue)
//   public/vendor/mediapipe/selfie_segmentation_solution_simd_wasm_bin.data
//   public/vendor/mediapipe/selfie_segmentation.binarypb         (graph)
//   public/vendor/mediapipe/selfie_segmentation*.tflite          (model)
//   public/vendor/mediapipe/LICENSE
//
// The handoff host chrome loads `/vendor/mediapipe/selfie_segmentation.js`
// same-origin and constructs `SelfieSegmentation({ locateFile: p =>
// '/vendor/mediapipe/' + p })`, so every asset resolves under the same origin.

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public/vendor/mediapipe");
const tmpDir = join(root, ".vendor-mediapipe-tmp");
const SPEC = "@mediapipe/selfie_segmentation@0.1.1675465747";
const PKG_NAME = "@mediapipe/selfie_segmentation";

function run(cmd, args, cwd) {
  const res = spawnSync(cmd, args, { cwd, stdio: "pipe" });
  if (res.status !== 0) {
    process.stderr.write(res.stderr?.toString() ?? "");
    throw new Error(`${cmd} ${args.join(" ")} exited ${res.status}`);
  }
}

rmSync(tmpDir, { recursive: true, force: true });
mkdirSync(tmpDir, { recursive: true });
run("npm", ["install", "--no-save", SPEC], tmpDir);

const pkgDir = join(tmpDir, "node_modules", PKG_NAME);
if (!existsSync(pkgDir)) {
  throw new Error(`expected ${pkgDir} after install; not found`);
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// Copy every file the package ships (js, wasm, data, tflite, binarypb).
// Skipping none: the WASM loader fetches them by name at runtime via
// locateFile, so a missing asset is a runtime failure.
const files = readdirSync(pkgDir).filter(
  (f) => f !== "package.json" && f !== "README.md" && f !== "index.d.ts",
);
for (const f of files) {
  copyFileSync(join(pkgDir, f), join(outDir, f));
}

// LICENSE — MediaPipe is Apache-2.0.
const licenseSrc = join(pkgDir, "README.md");
if (existsSync(licenseSrc)) {
  // The package ships no LICENSE file; the README carries the notice. Copy it
  // as LICENSE so the vendored dir is self-documenting.
  copyFileSync(licenseSrc, join(outDir, "LICENSE"));
}

rmSync(tmpDir, { recursive: true, force: true });

const out = `// Generated by scripts/vendor-mediapipe.mjs from ${SPEC}.
// Do not hand-edit; re-run the script to update. Served same-origin at
// /vendor/mediapipe/* (run_worker_first already lists /vendor/*).
`;
// Stamp a manifest so a stale vendoring is obvious.
const { writeFileSync } = await import("node:fs");
writeFileSync(
  join(outDir, "VERSION"),
  `${out}mediapipe selfie_segmentation ${SPEC.replace(/@[^@/]+$/, "")}\n`,
);

console.log(`vendored ${files.length} files to public/vendor/mediapipe/`);
